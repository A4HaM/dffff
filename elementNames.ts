const ELEMENT_NAME_ALIAS: Record<string, string> = {
  yue: 'zh-TW',
  wuu: 'zh',
  jv: 'id',
  su: 'id',
};

export function getElementName(element: ChemicalElement, lang: string): string {
  const resolved = ELEMENT_NAME_ALIAS[lang] ?? lang;
  const list = ELEMENT_NAMES_BY_LANG[resolved];
  if (list && list[element.number - 1]) {
    return list[element.number - 1];
  }
  return element.name;
}
