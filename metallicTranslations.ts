export function getQuizSubjectOptions(
  symbolToNameText: string,
  lang: string
): Array<{ id: 'symbol' | 'name' | 'number'; label: string }> {
  const parts = symbolToNameText.split(/\s*[→←]\s*/);
  const symbolWord = parts[0]?.trim() || 'Symbol';
  const nameWord = parts[1]?.trim() || 'Name';
  const key = ALIASES[lang] ?? lang;
  const atomicWord = ATOMIC_SUBJECT_BY_LANG[key] ?? ATOMIC_SUBJECT_BY_LANG.en;
  return [
    { id: 'symbol', label: symbolWord },
    { id: 'name', label: nameWord },
    { id: 'number', label: atomicWord },
  ];
}

